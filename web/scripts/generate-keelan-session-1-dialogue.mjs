import { mkdir, readFile, rename, stat, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";
import dotenv from "dotenv";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, "..");
dotenv.config({ path: path.join(webRoot, ".env.local") });

const dialoguePath = path.join(webRoot, "content", "voices", "keelan-session-1-dialogue-draft.md");
const voiceConfigPath = path.join(webRoot, "content", "voices", "keelan-voice-sample.json");
const outputDir = path.join(
  webRoot,
  "public",
  "curriculum",
  "grade-4-movers",
  "characters",
  "audio",
  "keelan",
  "session-1",
);
const generatedModulePath = path.join(webRoot, "lib", "curriculum", "session-1-dialogue.generated.ts");
const publicBase = "/curriculum/grade-4-movers/characters/audio/keelan/session-1";
const voice = "coral";
const force = process.argv.includes("--force");
const dryRun = process.argv.includes("--dry-run");

function parseDialogue(markdown) {
  const clips = [];
  const blockPattern = /^### `(s1-[^`]+)`\s*\r?\n([\s\S]*?)(?=^### `|^## |(?![\s\S]))/gm;
  for (const match of markdown.matchAll(blockPattern)) {
    const id = match[1];
    const block = match[2];
    const text = block.match(/\*\*Keelan:\*\*\s+“([^”]+)”/)?.[1]?.trim();
    if (!text) continue;
    const direction = block.match(/\*\*Direction:\*\*\s+([^\r\n]+)/)?.[1]?.trim() ?? "";
    clips.push({ id, text, direction });
  }
  const duplicates = clips.filter((clip, index) => clips.findIndex((item) => item.id === clip.id) !== index);
  if (duplicates.length) throw new Error(`Duplicate dialogue IDs: ${duplicates.map((clip) => clip.id).join(", ")}`);
  return clips;
}

async function isCompleteFile(filePath) {
  try {
    return (await stat(filePath)).size > 1000;
  } catch {
    return false;
  }
}

function wait(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

async function generateClip({ apiKey, config, clip }) {
  const outputPath = path.join(outputDir, `${clip.id}.${config.format}`);
  if (!force && await isCompleteFile(outputPath)) {
    console.log(`Kept    ${clip.id}`);
    return;
  }

  let lastError;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const response = await fetch("https://api.openai.com/v1/audio/speech", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: config.model,
          voice,
          input: clip.text,
          instructions: `${config.instructions}\n\nPerformance direction for this clip: ${clip.direction || "Keep the delivery playful, clear, and immediately actionable."}`,
          response_format: config.format,
          speed: config.speed,
        }),
      });
      if (!response.ok) {
        const detail = await response.text();
        throw new Error(`OpenAI speech generation failed (${response.status}): ${detail.slice(0, 500)}`);
      }
      const temporaryPath = `${outputPath}.tmp`;
      await writeFile(temporaryPath, Buffer.from(await response.arrayBuffer()));
      if (!await isCompleteFile(temporaryPath)) throw new Error("The generated audio file was unexpectedly small.");
      await rename(temporaryPath, outputPath);
      console.log(`Created ${clip.id}`);
      return;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await wait(attempt * 1200);
    }
  }
  throw lastError;
}

async function runPool(items, worker, concurrency = 4) {
  let cursor = 0;
  async function runWorker() {
    while (cursor < items.length) {
      const item = items[cursor];
      cursor += 1;
      await worker(item);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, runWorker));
}

async function writeManifests({ clips, config }) {
  const entries = Object.fromEntries(clips.map((clip) => [clip.id, {
    text: clip.text,
    audioUrl: `${publicBase}/${clip.id}.${config.format}`,
  }]));
  const manifest = {
    character: "Keelan",
    session: "grade-4-unit-1-session-1",
    protocol: config.sampleId,
    model: config.model,
    voice,
    format: config.format,
    speed: config.speed,
    clipCount: clips.length,
    clips: entries,
  };
  await writeFile(path.join(outputDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

  const moduleSource = `// Generated by scripts/generate-keelan-session-1-dialogue.mjs.\n// Edit content/voices/keelan-session-1-dialogue-draft.md, then regenerate.\n\nexport const SESSION_1_DIALOGUE = ${JSON.stringify(entries, null, 2)} as const;\n\nexport type Session1DialogueId = keyof typeof SESSION_1_DIALOGUE;\n`;
  await writeFile(generatedModulePath, moduleSource, "utf8");
}

async function main() {
  const [markdown, configText] = await Promise.all([
    readFile(dialoguePath, "utf8"),
    readFile(voiceConfigPath, "utf8"),
  ]);
  const clips = parseDialogue(markdown);
  if (clips.length !== 52) throw new Error(`Expected 52 approved clips, but parsed ${clips.length}.`);
  console.log(`Validated ${clips.length} Session 1 dialogue clips using Coral / ${JSON.parse(configText).sampleId}.`);
  if (dryRun) return;

  const apiKey = process.env.OPENAI_API_KEY?.trim();
  if (!apiKey) throw new Error("OPENAI_API_KEY is not configured in web/.env.local.");
  const config = JSON.parse(configText);
  await mkdir(outputDir, { recursive: true });
  await runPool(clips, (clip) => generateClip({ apiKey, config, clip }));

  const missing = [];
  for (const clip of clips) {
    if (!await isCompleteFile(path.join(outputDir, `${clip.id}.${config.format}`))) missing.push(clip.id);
  }
  if (missing.length) throw new Error(`Missing or incomplete clips: ${missing.join(", ")}`);
  await writeManifests({ clips, config });
  console.log(`Ready: ${clips.length}/${clips.length} clips plus manifest and typed dialogue map.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
